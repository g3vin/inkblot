					return
				}
			}
		}
		throw DecodingError.typeMismatch(BridgeRequest.self, DecodingError.Context(codingPath: decoder.codingPath, debugDescription: "Wrong type for BridgeRequest"))
	}

	public func encode(to encoder: Encoder) throws {
