#!/usr/bin/env node
/**
 * gen-spring-tokens.mjs — writes the `--spring-*` tokens in src/styles/tokens.css from
 * the springs in src/ui/physics.js, so CSS and script move on the same physics
 * (docs/DESIGN.md §7).
 *
 *   node scripts/gen-spring-tokens.mjs           rewrite the generated block
 *   node scripts/gen-spring-tokens.mjs --check   fail if the block is stale
 *
 * Each spring becomes three tokens: `--spring-<name>`, its curve as a CSS `linear()`
 * easing; `--spring-<name>-dur`, how long it takes to settle; and, for webviews
 * without `linear()` (older WebKitGTK), the closest `cubic-bezier` as the fallback.
 * `npm run lint:design` runs the check.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const TOKENS = path.join(repo, 'src/styles/tokens.css')
const BEGIN = '/* spring:begin'
const END = '/* spring:end */'

const { SPRINGS, spring, springAt, springEasing } = await import(pathToFileURL(path.join(repo, 'src/ui/physics.js')).href)
const { cubicBezier } = await import(pathToFileURL(path.join(repo, 'src/lib/sheetFlight.js')).href)

const round2 = (n) => Math.round(n * 100) / 100

/** The cubic-bézier nearest a spring from rest, by least squares over a coarse grid. */
function fallbackCurve(preset, duration) {
  const params = spring(preset)
  const samples = Array.from({ length: 40 }, (_, i) => (i + 1) / 41)
  const truth = samples.map((p) => springAt(params, 0, 1, 0, p * duration).value)
  let best = null
  for (let x1 = 0; x1 <= 0.6; x1 += 0.05) {
    for (let y1 = 0; y1 <= 1.6; y1 += 0.05) {
      for (let x2 = 0; x2 <= 0.6; x2 += 0.05) {
        const ease = cubicBezier(x1, y1, x2, 1)
        let error = 0
        for (let i = 0; i < samples.length; i += 1) error += (ease(samples[i]) - truth[i]) ** 2
        if (!best || error < best.error) best = { error, curve: [x1, y1, x2, 1] }
      }
    }
  }
  return `cubic-bezier(${best.curve.map(round2).join(', ')})`
}

export function springBlock() {
  const fallback = []
  const curves = []
  for (const [name, preset] of Object.entries(SPRINGS)) {
    const { easing, duration } = springEasing(preset)
    fallback.push(`  --spring-${name}: ${fallbackCurve(preset, duration)};`)
    fallback.push(`  --spring-${name}-dur: ${duration}ms;`)
    curves.push(`    --spring-${name}: ${easing};`)
  }
  return [
    `${BEGIN} — generated by scripts/gen-spring-tokens.mjs from src/ui/physics.js.`,
    '   Edit the springs there and rerun it; never edit these by hand. */',
    ':root {',
    ...fallback,
    '}',
    '@supports (transition-timing-function: linear(0, 1)) {',
    '  :root {',
    ...curves,
    '  }',
    '}',
    END,
  ].join('\n')
}

export function currentBlock(text) {
  const start = text.indexOf(BEGIN)
  const end = text.indexOf(END)
  return start === -1 || end === -1 ? null : text.slice(start, end + END.length)
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  const text = fs.readFileSync(TOKENS, 'utf8')
  const next = springBlock()
  const current = currentBlock(text)
  if (process.argv.includes('--check')) {
    if (current !== next) {
      console.error('✗ the --spring-* tokens are stale: run `node scripts/gen-spring-tokens.mjs`')
      process.exitCode = 1
    } else {
      console.log('✓ spring tokens match src/ui/physics.js')
    }
  } else if (current === null) {
    console.error(`✗ no ${BEGIN} … ${END} markers in src/styles/tokens.css`)
    process.exitCode = 1
  } else {
    fs.writeFileSync(TOKENS, text.replace(current, next))
    console.log('wrote the spring tokens')
  }
}
