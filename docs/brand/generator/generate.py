"""
generate.py — rebuild the Inkblot logo from its sources.

    pip install numpy scikit-image fonttools brotli
    python3 docs/brand/generator/generate.py

Writes src/ui/brandPaths.js (used by src/ui/Brand.jsx) and src/assets/brand/
{mark,wordmark,app-icon}.svg plus public/favicon.svg. The desktop and iOS icons are then
rasterised from app-icon.svg (see docs/design-handoff.md → Logo) and passed to
`npx tauri icon`.

The chosen splash is concept B3 "Spray": seed 11 in splash.py's model of an ink drop
hitting paper (70° impact, travelling up and to the right, We 420).
"""
import json
import re
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

from splash import render, splash

ROOT = Path(__file__).resolve().parents[3]
FONT = ROOT / 'node_modules/@fontsource/courier-prime/files/courier-prime-latin-700-normal.woff'

# The spray (mark units: 64×64, y down; core centred at 32,14.5, core radius 6.2).
SEED = 11
SPLASH = dict(seed=SEED, impact_deg=[62, 70, 78][SEED % 3], travel_deg=-35 - (SEED % 4) * 8,
              We=[300, 420, 560][SEED % 3], size=6.2, reach=[0.9, 1.1, 1.3][(SEED // 3) % 3])
spray = render(splash(**SPLASH))
STEM = 'M32 29 a5 5 0 0 1 5 5 v21 a5 5 0 0 1 -10 0 v-21 a5 5 0 0 1 5 -5 Z'
mark = spray + [STEM]


def ink_bounds(paths):
    xs, ys = [], []
    for d in paths:
        nums = [float(n) for n in re.findall(r'-?\d+(?:\.\d+)?', d)]
        xs += nums[0::2]
        ys += nums[1::2]
    return min(xs), min(ys), max(xs), max(ys)


# App icon: the stem on the tile's centre line, the ink optically centred. The spray's
# paths are absolute; the stem's box (27–37 × 29–60) is added by hand.
x0, y0, x1, y1 = ink_bounds(spray)
x0, x1, y1 = min(x0, 27), max(x1, 37), max(y1, 60)
scale = 40 / (y1 - y0)
icon_tx = 32 - 32 * scale
icon_ty = 32 - (y0 + (y1 - y0) / 2) * scale - 1
ICON_TRANSFORM = f'translate({icon_tx:.2f} {icon_ty:.2f}) scale({scale:.4f})'

# Wordmark: the mark's i at Courier Prime Bold's x-height and spacing, then "nkblot".
font = TTFont(FONT)
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
XH = font['OS/2'].sxHeight


def outline(ch, dx):
    rec = DecomposingRecordingPen(glyphs)
    glyphs[cmap[ord(ch)]].draw(rec)
    pen = SVGPathPen(glyphs)
    for op, args in rec.value:
        getattr(pen, op)(*[(x + dx, y) for (x, y) in args])
    return pen.getCommands()


def left_bearing(ch):
    pen = BoundsPen(glyphs)
    glyphs[cmap[ord(ch)]].draw(pen)
    return pen.bounds[0], pen.bounds[2]


STEM_W, SPRAY_SCALE, SPRAY_GAP, LSB, SPACE = 280, 24, 160, 70, 150
r = STEM_W / 2
cx = LSB + r
stem = (f'M{cx - r:.1f} {r:.1f} A{r:.1f} {r:.1f} 0 0 1 {cx + r:.1f} {r:.1f} '
        f'L{cx + r:.1f} {XH - r:.1f} A{r:.1f} {r:.1f} 0 0 1 {cx - r:.1f} {XH - r:.1f} Z')
spray_tx = cx - 32 * SPRAY_SCALE
spray_ty = XH + SPRAY_GAP + 20.7 * SPRAY_SCALE
adv = cx + r + SPACE - left_bearing('n')[0]
letters = []
for ch in 'nkblot':
    letters.append(outline(ch, adv))
    adv += glyphs[cmap[ord(ch)]].width
width = adv - (glyphs[cmap[ord('t')]].width - left_bearing('t')[1]) + 40
left = min(0, spray_tx + x0 * SPRAY_SCALE - 20)
top = int(spray_ty - y0 * SPRAY_SCALE + 30)
height = top + 60
WORDMARK = dict(
    viewBox=f'{left:.0f} 0 {width - left:.0f} {height}',
    flip=f'matrix(1 0 0 -1 0 {top})',
    shapes=stem + ' ' + ' '.join(letters),
    sprayTransform=f'matrix({SPRAY_SCALE:.3f} 0 0 {-SPRAY_SCALE:.3f} {spray_tx:.1f} {spray_ty:.1f})',
    spray=spray,
)

js = f"""/**
 * brandPaths.js — the Inkblot mark and wordmark as path data. Generated by
 * docs/brand/generator/generate.py (do not edit by hand): the spray is drawn by a model
 * of an ink drop hitting paper, the wordmark's "nkblot" from Courier Prime Bold's outlines.
 */

/** The mark: a lowercase i whose dot is an ink spray. viewBox 0 0 64 64. */
export const MARK_PATHS = {json.dumps(mark, indent=2)}

/** Where the mark sits in the 64×64 app-icon tile: its stem on the centre line, its ink
 *  optically centred (a unit above the middle). */
export const ICON_TRANSFORM = '{ICON_TRANSFORM}'

/** The wordmark: the mark's i (pill stem + spray) set in Courier Prime Bold's x-height
 *  and spacing, then "nkblot". Font units, y up, flipped by `flip`. */
export const WORDMARK = {json.dumps(WORDMARK, indent=2)}
"""
(ROOT / 'src/ui/brandPaths.js').write_text(js)

paths = ''.join(f'<path d="{d}"/>' for d in mark)
brand = ROOT / 'src/assets/brand'
brand.mkdir(parents=True, exist_ok=True)
(brand / 'mark.svg').write_text(
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" fill="#000" role="img" aria-label="Inkblot">{paths}</svg>\n')
icon = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" role="img" aria-label="Inkblot">'
        f'<rect width="64" height="64" rx="14" fill="#fff"/><g fill="#000" transform="{ICON_TRANSFORM}">{paths}</g></svg>\n')
(brand / 'app-icon.svg').write_text(icon)
(ROOT / 'public/favicon.svg').write_text(icon)
spray_svg = ''.join(f'<path d="{d}"/>' for d in spray)
(brand / 'wordmark.svg').write_text(
    f'<svg xmlns="http://www.w3.org/2000/svg" fill="#000" viewBox="{WORDMARK["viewBox"]}" role="img" aria-label="inkblot">'
    f'<g transform="{WORDMARK["flip"]}"><path d="{WORDMARK["shapes"]}"/>'
    f'<g transform="{WORDMARK["sprayTransform"]}">{spray_svg}</g></g></svg>\n')
print('wrote brandPaths.js, mark.svg, wordmark.svg, app-icon.svg, favicon.svg')
