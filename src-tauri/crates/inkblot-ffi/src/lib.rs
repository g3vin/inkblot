//! inkblot-ffi — `inkblot-core`, as the Swift shell sees it.
//!
//! The core is shell-independent Rust with Rust-shaped APIs: borrowed strings, typed
//! scopes, serde values. UniFFI needs owned values and a small vocabulary of types, so
//! this crate is the translation, and only the translation. Nothing is decided here
//! that the Tauri shim in `src-tauri/src/*_commands.rs` does not also decide, because
//! both shells have to agree on what is on disk.
//!
//! **Why structured values cross as JSON strings.** Every domain type already has a
//! generated `Codable` twin in `InkblotCore.swift`, produced by typeshare from the same
//! Rust definition. Re-describing `TreeNode` to UniFFI would give Swift a *second*
//! `TreeNode`, generated by a second tool, that could drift from the first. A JSON
//! string decoded into the typeshare type keeps one definition — the property
//! `npm run types:check` exists to protect.
//!
//! **Why this is a separate crate rather than attributes on `inkblot-core`.** The
//! Tauri app links the core as an rlib and has no use for UniFFI's scaffolding; keeping
//! the macros out of it keeps the core exactly what `lib.rs` says it is — domain logic
//! that knows nothing about any shell.

use std::sync::Arc;

use inkblot_core::store::preferences::{PreferenceScope, PreferenceStore};
use inkblot_core::store::{DocumentBody, ProjectStore, StoreError};

uniffi::setup_scaffolding!();

/// Everything the core can refuse, flattened to a message.
///
/// The Swift callers either surface the message or fall back, exactly as the webview's
/// callers do with the strings the Tauri commands reject with. A richer error type
/// would be a promise of handling nobody has written.
#[derive(Debug, uniffi::Error)]
#[uniffi(flat_error)]
pub enum CoreError {
    Failed(String),
}

impl std::fmt::Display for CoreError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            CoreError::Failed(message) => write!(f, "{message}"),
        }
    }
}

impl std::error::Error for CoreError {}

impl From<StoreError> for CoreError {
    fn from(error: StoreError) -> Self {
        CoreError::Failed(error.to_string())
    }
}

impl From<serde_json::Error> for CoreError {
    fn from(error: serde_json::Error) -> Self {
        CoreError::Failed(error.to_string())
    }
}

fn scope_of(name: &str) -> Result<PreferenceScope, CoreError> {
    PreferenceScope::parse(name)
        .ok_or_else(|| CoreError::Failed(format!("Unknown preference scope: {name}")))
}

/// The core, rooted at one AppData directory.
///
/// One per app. The stores inside hold caches and per-document locks, so two of these
/// over the same directory would each believe they were the only writer.
#[derive(uniffi::Object)]
pub struct InkblotCore {
    projects: ProjectStore,
    preferences: PreferenceStore,
}

#[uniffi::export]
impl InkblotCore {
    /// `app_data_root` must be the directory Tauri's `appDataDir()` resolves to
    /// (`~/Library/Application Support/com.inkblot.app`), so both shells open the
    /// same projects and read the same preferences.
    #[uniffi::constructor]
    pub fn new(app_data_root: String, session_id: String) -> Arc<Self> {
        Arc::new(Self {
            projects: ProjectStore::new(&app_data_root, &session_id),
            preferences: PreferenceStore::new(&app_data_root),
        })
    }

    pub fn app_data_root(&self) -> String {
        self.projects.app_data_root().to_string()
    }

    /* ---------------- preferences ---------------- */

    /// Every scope at once, as `{ scope: { key: value } }` — the same shape
    /// `preferences_load` hands the webview.
    pub fn preferences_load_json(&self) -> Result<String, CoreError> {
        Ok(serde_json::to_string(&self.preferences.load_all())?)
    }

    pub fn preferences_get(&self, scope: String, key: String) -> Result<Option<String>, CoreError> {
        Ok(self.preferences.get(scope_of(&scope)?, &key))
    }

    pub fn preferences_set(&self, scope: String, key: String, value: String) -> Result<(), CoreError> {
        Ok(self.preferences.set(scope_of(&scope)?, &key, &value)?)
    }

    pub fn preferences_remove(&self, scope: String, key: String) -> Result<(), CoreError> {
        Ok(self.preferences.remove(scope_of(&scope)?, &key)?)
    }

    pub fn preferences_rename_prefix(
        &self,
        scope: String,
        from_prefix: String,
        to_prefix: String,
    ) -> Result<(), CoreError> {
        Ok(self.preferences.rename_prefix(scope_of(&scope)?, &from_prefix, &to_prefix)?)
    }

    /* ---------------- projects ---------------- */

    /// Unsorted, as the core returns it; presentation is the picker's decision.
    pub fn list_projects(&self) -> Vec<String> {
        self.projects.list_projects()
    }

    pub fn project_root(&self, project_name: String) -> String {
        self.projects.project_root(&project_name)
    }

    /// A project's tree as a `TreeNode`, JSON-encoded — see the module note.
    pub fn project_tree_json(&self, project_name: String) -> Result<String, CoreError> {
        Ok(serde_json::to_string(&self.projects.list_project_tree(&project_name))?)
    }

    pub fn create_project(
        &self,
        project_name: String,
        target_parent_dir: Option<String>,
    ) -> Result<bool, CoreError> {
        Ok(self.projects.create_project(&project_name, target_parent_dir.as_deref())?)
    }

    pub fn create_folder(&self, project_name: String, folder_path: String) -> Result<(), CoreError> {
        Ok(self.projects.create_folder(&project_name, &folder_path)?)
    }

    pub fn document_exists(&self, project_name: String, doc_name: String) -> bool {
        self.projects.document_exists(&project_name, &doc_name)
    }

    /// A new, empty text document — `{ content: [], notes: [], versions: [] }`, which is
    /// what the web tree's "New Document" writes through `saveDocument`. Through the
    /// core's `save_document` rather than a raw write, so the key whitelist is the one
    /// both shells share.
    ///
    /// Refuses an existing document rather than emptying it: the caller picked a name,
    /// and a name that is taken is a question for the user, not a reason to lose a file.
    pub fn create_document(&self, project_name: String, doc_name: String) -> Result<(), CoreError> {
        if self.projects.document_exists(&project_name, &doc_name) {
            return Err(CoreError::Failed(format!("{doc_name} already exists")));
        }
        let body = DocumentBody {
            content: serde_json::json!([]),
            notes: serde_json::json!([]),
        };
        Ok(self.projects.save_document(&project_name, &doc_name, &body, None)?)
    }
}

/* ---------------- free functions ---------------- */

/// Installed font families, sorted and without Apple's private dot-faces.
#[uniffi::export]
pub fn list_system_fonts() -> Result<Vec<String>, CoreError> {
    inkblot_core::fonts::list_system_fonts().map_err(CoreError::Failed)
}

#[uniffi::export]
pub fn is_canvas_doc(path: String) -> bool {
    inkblot_core::doc_kind::is_canvas_doc(&path)
}

/// What a document is called in the UI: its last path segment, without `.canvas`.
#[uniffi::export]
pub fn doc_display_name(path: String) -> String {
    inkblot_core::doc_kind::get_doc_display_name(&path)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn scratch_root(label: &str) -> String {
        let dir = std::env::temp_dir().join(format!(
            "inkblot-ffi-{label}-{}-{}",
            std::process::id(),
            inkblot_core::store::clock::now_millis()
        ));
        std::fs::create_dir_all(&dir).unwrap();
        dir.to_string_lossy().to_string()
    }

    #[test]
    fn preferences_round_trip_through_the_json_the_webview_reads() {
        let core = InkblotCore::new(scratch_root("prefs"), "s".into());
        core.preferences_set("app".into(), "theme".into(), "\"dark\"".into()).unwrap();

        let loaded: serde_json::Value =
            serde_json::from_str(&core.preferences_load_json().unwrap()).unwrap();
        assert_eq!(loaded["app"]["theme"], "\"dark\"");
        assert_eq!(
            core.preferences_get("app".into(), "theme".into()).unwrap().as_deref(),
            Some("\"dark\"")
        );
    }

    #[test]
    fn an_unknown_scope_is_an_error_not_a_path() {
        let core = InkblotCore::new(scratch_root("scope"), "s".into());
        assert!(core.preferences_set("../escape".into(), "k".into(), "v".into()).is_err());
    }

    #[test]
    fn a_project_tree_crosses_as_the_typeshare_shape() {
        let core = InkblotCore::new(scratch_root("tree"), "s".into());
        assert!(core.create_project("Novel".into(), None).unwrap());
        core.create_folder("Novel".into(), "Part One".into()).unwrap();

        let tree: serde_json::Value =
            serde_json::from_str(&core.project_tree_json("Novel".into()).unwrap()).unwrap();
        assert_eq!(tree["type"], "folder");
        assert_eq!(tree["name"], "Novel");
        assert_eq!(tree["children"][0]["name"], "Part One");
        assert_eq!(core.list_projects(), vec!["Novel".to_string()]);
    }

    #[test]
    fn a_new_document_is_the_shape_the_web_tree_writes_and_never_overwrites() {
        let root = scratch_root("create");
        let core = InkblotCore::new(root.clone(), "s".into());
        core.create_project("Novel".into(), None).unwrap();
        core.create_document("Novel".into(), "Part One/Chapter 1".into()).unwrap();

        let written: serde_json::Value = serde_json::from_str(
            &std::fs::read_to_string(format!("{root}/Novel/Part One/Chapter 1.json")).unwrap(),
        )
        .unwrap();
        assert_eq!(written, serde_json::json!({ "content": [], "notes": [], "versions": [] }));

        assert!(core.create_document("Novel".into(), "Part One/Chapter 1".into()).is_err());
        assert!(core.create_document("Novel".into(), "board.canvas".into()).is_err());
    }
}
